# ============================================================
# config.py —— 项目配置文件
#
# 作用：把所有"可能需要修改的设置"集中放在这一个地方。
# 以后改数据库地址、改密钥，只需要动这一个文件，
# 不需要满项目到处找。
# ============================================================

import os
import secrets


class Config:
    # --------------------------------------------------------
    # Flask 密钥
    # 作用：用来给 session（登录状态）加密，防止被篡改。
    # 优先从环境变量读取，若未设置则自动生成随机密钥（开发时可用）
    # 生产部署时务必在环境变量中设置固定值，否则每次重启都会使旧 Session 失效
    # 设置方式：export SECRET_KEY="你的随机字符串"
    # --------------------------------------------------------
    SECRET_KEY = os.environ.get('SECRET_KEY') or secrets.token_hex(32)

    # --------------------------------------------------------
    # 上传文件夹路径
    # 作用：用户上传的 PDF 文件会存放在这个文件夹里。
    # os.path.join 会自动根据操作系统拼接路径，
    # 比如 Windows 上会变成  uploads\
    # --------------------------------------------------------
    UPLOAD_FOLDER = os.path.join(os.path.dirname(__file__), "uploads")

    # --------------------------------------------------------
    # 单个上传文件的最大体积限制：50MB
    # 1024 * 1024 = 1MB，乘以 50 就是 50MB
    # --------------------------------------------------------
    MAX_CONTENT_LENGTH = 50 * 1024 * 1024

    # --------------------------------------------------------
    # 数据库连接字符串
    # 作用：告诉 pyodbc 去哪台服务器、连哪个数据库。
    #
    # DRIVER   : 使用的数据库驱动，SQL Server 固定写这个
    # SERVER   : 你的数据库服务器名称（和你原项目保持一致）
    # DATABASE : 数据库名称
    # Trusted_Connection=yes : 使用 Windows 身份验证登录，
    #            不需要输入用户名密码（和你原项目一样）
    #
    # 如果将来部署到 Linux 服务器，需要安装 ODBC Driver 17/18，
    # 并修改 DRIVER 为 'ODBC Driver 17 for SQL Server'
    # --------------------------------------------------------
    DB_CONNECTION_STRING = (
        'DRIVER={SQL Server};'
        'SERVER=destiny;'
        'DATABASE=AcademicSearchDB;'
        'Trusted_Connection=yes;'
    )